"""Render models/tuning.json as docs/TUNING.md. Every number comes from the file; nothing is typed by hand.

    python -m src.ml.tune_report
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

import numpy as np

from src import config
from src.ml.tune_stats import SEARCHED

TUNING_MD: Path = config.PROJECT_ROOT / "docs" / "TUNING.md"
TEST_ROWS = (
    ("PR-AUC", "pr_auc"), ("ROC-AUC", "roc_auc"), ("Precision", "precision"), ("Recall", "recall"),
    ("F1", "f1"), ("Accuracy", "accuracy"), ("Brier (lower is better)", "brier"),
)


def load_report(path: Path = config.TUNING_JSON) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _num(value: Any) -> str:
    if value is None:
        return "-"
    return f"{value:.4g}" if isinstance(value, float) else str(value)


def _finalist_params(report: dict[str, Any]) -> list[dict[str, Any]]:
    rows = {row["index"]: row for row in report["stage1"]}
    return [rows[index]["params"] for index in report["finalists"]]


def shared_values(report: dict[str, Any]) -> dict[str, Any]:
    """Searched parameters that have the same value in every finalist."""
    params = _finalist_params(report)
    if not params:
        return {}
    return {key: params[0][key] for key in SEARCHED if len({repr(p[key]) for p in params}) == 1}


def _stage1_table(report: dict[str, Any]) -> list[str]:
    rows = {row["index"]: row for row in report["stage1"]}
    lines = ["| arm | PR-AUC, mean +/- std over folds | mean Brier |", "|---|---|---|"]
    for index in [0, *report["finalists"]]:
        row = rows[index]
        name = "baseline" if index == 0 else f"configuration {index}"
        lines.append(f"| {name} | {row['pr_mean']} +/- {row['pr_std']} | {row['brier_mean']} |")
    return lines


def _stage2_table(report: dict[str, Any]) -> list[str]:
    lines = ["| arm | PR-AUC, mean +/- std over folds | mean Brier |", "|---|---|---|"]
    for arm in report["stage2"]:
        name = "baseline" if arm["index"] == 0 else f"configuration {arm['index']}"
        lines.append(
            f"| {name} | {np.mean(arm['pr']):.4f} +/- {np.std(arm['pr'], ddof=1):.4f} | {np.mean(arm['brier']):.4f} |"
        )
    return lines


def _params_table(report: dict[str, Any]) -> list[str]:
    lines = ["| arm | " + " | ".join(SEARCHED) + " |", "|---|" + "---|" * len(SEARCHED)]
    lines.append("| baseline | " + " | ".join(_num(report["baseline_params"].get(key)) for key in SEARCHED) + " |")
    for index, params in zip(report["finalists"], _finalist_params(report)):
        lines.append(f"| configuration {index} | " + " | ".join(_num(params[key]) for key in SEARCHED) + " |")
    return lines


def render_markdown(report: dict[str, Any]) -> str:
    """The full docs/TUNING.md text."""
    d, rule = report["decision"], report["rule"]
    adopted = bool(report["adopted"])
    best_arm = report["finalists"][d["best"]]
    means = [row["pr_mean"] for row in report["stage1"][1:]]
    baseline = report["stage1"][0]
    shared = shared_values(report)
    t_text = "n/a" if d["t"] is None else d["t"]
    shared_text = (
        "Parameters with the same value in every finalist: "
        + ", ".join(f"{key} = {_num(value)}" for key, value in shared.items())
        + ". A parameter that every finalist pushed to the same value may sit at the edge of the search range."
        if shared else "No parameter has the same value in every finalist."
    )
    out = [
        "# XGBoost tuning experiment", "",
        "Generated by `python -m src.ml.tune_report` from `models/tuning.json`. Do not edit by hand.", "",
        f"**Outcome: {'a tuned model was adopted' if adopted else 'the baseline was kept'}.**", "",
        "## Protocol (fixed before the first run)", "",
        f"- Training split only ({report['n_train']} customers). The test split plays no part in the search or the decision.",
        f"- {report['n_configs']} seeded random XGBoost configurations plus the baseline, scored with repeated stratified "
        f"{config.CV_FOLDS}-fold cross-validation ({rule['repeats_search']} repeats) on the same folds, so scores are paired.",
        f"- The best {rule['top_k']} by mean PR-AUC and the baseline were re-scored on fresh folds ({rule['repeats_confirm']} repeats).",
        f"- Adoption needs all of: a mean PR-AUC gain of at least {rule['min_gain']}; a corrected one-sided paired t-test "
        f"below {rule['alpha']} divided by {rule['top_k']}; and a mean Brier score no worse by more than {rule['max_brier_worse']}.",
        "- No early stopping, because it would score each round on the validation fold.", "",
        "## Stage 1: search", "",
        f"Across the {len(means)} random configurations, mean PR-AUC ranged from {min(means)} to {max(means)} "
        f"(median {statistics.median(means)}). The baseline scored {baseline['pr_mean']}.", "",
        *_stage1_table(report), "",
        "Parameters (a dash means the baseline left the parameter at the library default):", "",
        *_params_table(report), "", shared_text, "",
        "## Stage 2: confirmation on fresh folds", "", *_stage2_table(report), "",
        "## Decision", "",
        f"- Best finalist on the fresh folds: configuration {best_arm}.",
        f"- Mean PR-AUC gain over the baseline: {d['mean_gain']} (required: at least {rule['min_gain']}).",
        f"- Standard deviation of the paired fold differences: {d['sd_diff']}.",
        f"- Corrected paired t-test, one-sided: t = {t_text}, df = {d['df']}, p = {d['p_value']} "
        f"(required: below {d['alpha']}, which is {rule['alpha']} divided by {rule['top_k']}).",
        f"- Change in mean Brier score: {d['brier_diff']} (negative is better; adoption needs no worsening beyond {rule['max_brier_worse']}).",
        "",
    ]
    out += (["Not adopted because:", "", *[f"- {reason}" for reason in d["reasons"]], ""] if d["reasons"] else ["Every gate was passed.", ""])
    out += ["## Test split", ""]
    if adopted and report.get("test") and report.get("baseline_test"):
        base, tuned = report["baseline_test"], report["test"]
        out += ["| metric | baseline | tuned |", "|---|---|---|"]
        out += [f"| {label} | {base[key]} | {tuned[key]} |" for label, key in TEST_ROWS]
    else:
        out.append("The test split was not scored for any tuned configuration.")
    out += [
        "", "## How to read this", "",
        "- PR-AUC measures how well customers are ranked. Brier measures probability error and is sensitive to class "
        "weighting, so a Brier gain here does not by itself mean better ranking.",
        "- Folds of repeated cross-validation share training rows. The Nadeau-Bengio correction accounts for that "
        "approximately, so the p-value is a guide, not a proof.",
        f"- Picking the best of {rule['top_k']} finalists on the same folds is why the significance level is divided by {rule['top_k']}.",
        f"- Run time: {report['elapsed_s']} s.", "",
    ]
    return "\n".join(out)


def main() -> None:
    """CLI: python -m src.ml.tune_report"""
    TUNING_MD.parent.mkdir(parents=True, exist_ok=True)
    TUNING_MD.write_text(render_markdown(load_report()), encoding="utf-8", newline="\n")
    print(f"wrote {TUNING_MD}")


if __name__ == "__main__":
    main()