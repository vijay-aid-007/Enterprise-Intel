"""Generate docs/RESULTS.md, and the 'at a glance' block of README.md, from the files in eval/results.

Nothing is computed or typed by hand: every number comes from a results file written by an eval script or from
models/metrics.json. Held-out numbers are read from the *_FROZEN files, the single run made after prompts,
thresholds and the retrieval mode were frozen. Re-run after any eval re-run:

    python -m scripts.make_results_md [--readme README.md]
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from eval import agent_eval, generation_eval, ml_eval, retrieval_eval
from src import config

RESULTS_MD: Path = config.PROJECT_ROOT / "docs" / "RESULTS.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
GLANCE_K = 5  # must be one of config.EVAL_KS
SOURCES: dict[str, str] = {
    "retrieval_dev": "retrieval_dev.json",
    "retrieval_heldout": "retrieval_heldout_FROZEN.json",
    "generation_dev": "generation_dev.json",
    "generation_heldout": "generation_heldout_FROZEN.json",
    "agent": "agent_routing.json",
    "ml": "ml_eval.json",
}


def load_results(results_dir: Path = config.RESULTS_DIR) -> dict[str, Any]:
    """Read every source file. Raises FileNotFoundError naming all that are missing."""
    data: dict[str, Any] = {}
    missing: list[str] = []
    for key, name in SOURCES.items():
        path = results_dir / name
        if path.exists():
            data[key] = json.loads(path.read_text(encoding="utf-8"))
        else:
            missing.append(name)
    if missing:
        raise FileNotFoundError("missing results files (run the eval scripts first): " + ", ".join(missing))
    return data


def demote(markdown: str) -> str:
    """Push every heading one level down so each report nests under the RESULTS.md title."""
    return "\n".join("#" + line if line.startswith("#") else line for line in markdown.splitlines())


def generation_section(split: str, result: dict[str, Any]) -> str:
    """Generation report without the hand-check list (its blanks belong to a review, not to published results)."""
    text = generation_eval.render_markdown(split, result, {})
    head, _, tail = text.partition("## Hand check")
    cache = [line for line in tail.splitlines() if line.startswith("Cache:")]
    return head.rstrip() + "\n\n" + "\n".join(cache) + "\n"


def build_results(data: dict[str, Any], metrics: dict[str, Any]) -> str:
    """Full docs/RESULTS.md text."""
    ks = config.EVAL_KS
    intro = [
        "# Results", "",
        "Generated by `python -m scripts.make_results_md` from the files in `eval/results/` and `models/metrics.json`. "
        "Do not edit by hand. Held-out numbers come from the `_FROZEN` files: one run, made after prompts, "
        "thresholds and the retrieval mode were frozen.", "",
        "Gold questions were written from the SYNTHETIC documents, so retrieval and generation scores are optimistic. "
        "Samples are small and there are no confidence intervals, so read counts, not percentages.", "",
        f"`DENSE_MIN_SIM` was frozen at {config.DENSE_MIN_SIM} from the dev split alone. The 'suggested threshold' line "
        "in each retrieval report is informational and was not used to choose it.", "",
        "A cache line such as 'N replayed' means that run replayed recorded model replies. The numbers in those runs "
        "were first produced by live model calls.", "",
    ]
    sections = [
        demote(retrieval_eval.render_markdown("dev", data["retrieval_dev"], ks)),
        demote(retrieval_eval.render_markdown("heldout", data["retrieval_heldout"], ks)),
        demote(generation_section("dev", data["generation_dev"])),
        demote(generation_section("heldout", data["generation_heldout"])),
        demote(agent_eval.render_markdown(data["agent"])),
        demote(ml_eval.render_markdown(metrics, data["ml"])),
    ]
    return "\n".join(intro) + "\n" + "\n\n".join(section.rstrip() for section in sections) + "\n"


def _hits(ablation: dict[str, Any], k: int) -> str:
    return ", ".join(f"{mode} {s[f'hit@{k}']['hits']}/{s['n']}" for mode, s in ablation.items())


def _mrr(ablation: dict[str, Any]) -> str:
    return ", ".join(f"{mode} {s['mrr']}" for mode, s in ablation.items())


def glance(data: dict[str, Any], metrics: dict[str, Any]) -> str:
    """Compact results table for the README, every value read from the data."""
    held, dev = data["retrieval_heldout"]["ablation"], data["retrieval_dev"]["ablation"]
    table, rej = data["generation_heldout"]["table"], data["generation_heldout"]["rejection"]
    ans, oos, gap = table["answerable"], table["out_of_scope"], table["gap"]
    agent, test = data["agent"], metrics["test"]
    inj = agent["injection"]
    injection = (
        f"model complied: {inj['model_complied']}, shown to the user: {inj['shown_to_user']}" if inj else "not run"
    )
    rows = [
        (f"Retrieval hit@{GLANCE_K}, held-out", _hits(held, GLANCE_K)),
        ("Retrieval MRR, held-out", _mrr(held)),
        (f"Retrieval hit@{GLANCE_K}, dev", _hits(dev, GLANCE_K)),
        ("Answers to answerable questions, held-out",
         f"{ans.get('correct', 0)} correct, {ans.get('answered_incomplete', 0)} incomplete, "
         f"{ans.get('refused', 0)} refused of {ans['n']} (automatic fact matching, a lower bound)"),
        ("Refusals, held-out",
         f"out-of-scope {oos.get('refused', 0)}/{oos['n']}, unsupported but in-scope-looking {gap.get('refused', 0)}/{gap['n']}"),
        ("Validator rejections, held-out", f"{rej['rejected']} of {rej['reached_llm']} drafts that reached the model"),
        ("Agent routing (first tool)",
         f"{agent['routing']['ok']}/{agent['routing']['n']} (prompts not used in development: "
         f"{agent['routing_unseen']['ok']}/{agent['routing_unseen']['n']})"),
        ("Prompt injection, one case", injection),
        (f"Churn model, test split (n = {metrics['n_test']})",
         f"PR-AUC {test['pr_auc']}, ROC-AUC {test['roc_auc']}, precision {test['precision']}, recall {test['recall']} "
         f"at threshold {metrics['threshold']['value']}"),
    ]
    lines = ["| Measure | Result |", "|---|---|"] + [f"| {name} | {value} |" for name, value in rows]
    lines += [
        "",
        "Generated from `eval/results` by `scripts/make_results_md.py`. Gold questions come from SYNTHETIC documents, "
        "so scores are optimistic; samples are small and there are no confidence intervals. "
        "Full tables: [docs/RESULTS.md](docs/RESULTS.md).",
    ]
    return "\n".join(lines)


def update_block(readme: str, block: str) -> str:
    """Replace the text between the RESULTS markers. Raises ValueError unless there is exactly one pair."""
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise ValueError(f"README needs exactly one {START} and one {END} marker")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    return pattern.sub(lambda match: f"{START}\n{block}\n{END}", readme)


def main() -> None:
    """CLI: python -m scripts.make_results_md [--readme README.md]"""
    parser = argparse.ArgumentParser(description="Write docs/RESULTS.md from eval/results.")
    parser.add_argument("--readme", type=Path, default=None, help="also refresh the RESULTS block in this README")
    args = parser.parse_args()
    config.configure_logging()
    data, metrics = load_results(), ml_eval.load_metrics()
    RESULTS_MD.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_MD.write_text(build_results(data, metrics), encoding="utf-8", newline="\n")
    print(f"wrote {RESULTS_MD}")
    if args.readme:
        text = args.readme.read_text(encoding="utf-8")
        args.readme.write_text(update_block(text, glance(data, metrics)), encoding="utf-8", newline="\n")
        print(f"updated the results block in {args.readme}")


if __name__ == "__main__":
    main()